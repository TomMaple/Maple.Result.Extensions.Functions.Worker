using System.Collections.Generic;
using System.Text.Json.Serialization;

namespace Maple.Result.Extensions.Functions.Worker.ViewModels;

/// <summary>
///     Represents a problem details object as defined by RFC 9457.
/// </summary>
/// <remarks>
///     The Azure Functions isolated worker model does not reference ASP.NET Core, so it provides neither
///     the <c>ProblemDetails</c> type nor a helper producing an RFC 9457 response.
///     This type is based on the <c>ProblemDetails</c> type in the <c>Microsoft.AspNetCore.Mvc</c> namespace.
///     <list type="bullet">
///         <item>
///             <seealso href="https://learn.microsoft.com/en-us/dotnet/api/microsoft.aspnetcore.mvc.problemdetails" />
///         </item>
///         <item>
///             <seealso
///                 href="https://github.com/dotnet/aspnetcore/blob/main/src/Http/Http.Abstractions/src/ProblemDetails/ProblemDetails.cs" />
///         </item>
///     </list>
/// </remarks>
public sealed record ProblemDetails
{
    /// <summary>
    ///     Gets the URI reference that identifies the problem type.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("type")]
    public string? Type { get; init; }

    /// <summary>
    ///     Gets the short, human-readable summary of the problem type.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("title")]
    public string? Title { get; init; }

    /// <summary>
    ///     Gets the HTTP status code generated by the origin server for this occurrence of the problem.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("status")]
    public int? Status { get; init; }

    /// <summary>
    ///     Gets the human-readable explanation specific to this occurrence of the problem.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("detail")]
    public string? Detail { get; init; }

    /// <summary>
    ///     Gets the URI reference that identifies the specific occurrence of the problem.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("instance")]
    public string? Instance { get; init; }

    /// <summary>
    ///     Gets the additional members of the problem details object, serialized alongside the members
    ///     defined by RFC 9457.
    /// </summary>
    [JsonExtensionData]
    public IDictionary<string, object?>? Extensions { get; init; }
}
